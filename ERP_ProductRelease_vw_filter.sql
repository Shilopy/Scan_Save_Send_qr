-- ============================================================
-- Фильтр: исключение списка артикулов
-- Условия: Quantity > 0, Dt только 2024-2026
-- Колонка Palle_q-ty = 1 (каждая строка = 1 паллета)
-- Сортировка по Product No
-- Только первые 20 строк для просмотра
-- СУБД: SQL Server
-- ============================================================

SELECT TOP 20 *,
    1 AS [Palle_q-ty]
FROM ERP_ProductRelease_vw
WHERE [Product No] NOT IN (
    '509854', '509908', '510137', '599001', '599003',
    '599005', '599007', '599009', '599011', '599013',
    '599015', '599017', '599019', '599021', '599035',
    '599037', '599039', '599041', '599043'
)
  AND [Quantity] > 0
  AND YEAR([Dt]) IN (2024, 2025, 2026)
ORDER BY [Product No];
